export function pickRandomCar(excludeId?: string): CarDef {
  const pool = excludeId ? CAR_CATALOG.filter((c) => c.id !== excludeId) : CAR_CATALOG
  return pool[Math.floor(Math.random() * pool.length)]!
}

export function getCarById(id: string): CarDef | undefined {
  return CAR_CATALOG.find((c) => c.id === id)
}
